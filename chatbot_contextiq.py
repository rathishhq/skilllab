def simple_rag_answer(question):
    question = question.strip()
    if not question:
        return "Please enter a question."

    try:
        # Create question embedding
        query_vector = ollama_embed([question])[0]
        query_vector = query_vector / (np.linalg.norm(query_vector) + 1e-10)

        # Retrieve relevant chunks
        scores = chunk_vectors @ query_vector
        best_indices = np.argsort(scores)[::-1][:3]

        # Build context
        context = "\n\n".join(
            chunks[int(i)]["text"]
            for i in best_indices
        )

        # Create prompt
        prompt = f"""
You are an AI and Machine Learning knowledge assistant.

Answer using ONLY the supplied context.
If the answer is not available, say:
"I couldn't find that information in the knowledge base."

CONTEXT:
{context}

QUESTION:
{question}

ANSWER:
"""

        # Generate answer using Ollama
        response = requests.post(
            f"{OLLAMA_API}/api/generate",
            json={
                "model": CHAT_MODEL,
                "prompt": prompt,
                "stream": False,
                "options": {
                    "temperature": 0.2,
                    "num_predict": 250
                }
            },
            timeout=300
        )
        response.raise_for_status()
        answer = response.json()["response"].strip()

        # Show retrieved sources
        sources = "\n\n---\n\n### Retrieved Sources\n\n"
        for rank, idx in enumerate(best_indices, start=1):
            item = chunks[int(idx)]
            sources += (
                f"**{rank}. {item['source']}** "
                f"| Chunk {item['chunk_id']} "
                f"| Similarity: {scores[idx]:.3f}\n\n"
            )
        return answer + sources

    except requests.exceptions.RequestException as error:
        return f"**Connection error:** {str(error)}"
    except Exception as error:
        return f"**Error:** {str(error)}"


