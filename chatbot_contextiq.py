"""## 6. Retrieve relevant chunks and generate an answer

The `ask()` function performs semantic retrieval, builds a context-grounded prompt, calls Qwen through Ollama, and displays the source chunks it used.
"""

def ask(question, top_k=3):
    if not question.strip():
        print('Please enter a question.')
        return

    query_vector = ollama_embed([question])[0]
    query_vector = query_vector / (np.linalg.norm(query_vector) + 1e-10)

    scores = chunk_vectors @ query_vector
    best_indices = np.argsort(scores)[::-1][:min(top_k, len(chunks))]
    selected = [chunks[i] for i in best_indices]

    context_parts = []
    for number, item in enumerate(selected, start=1):
        context_parts.append(
            f"[Source {number}: {item['source']}, chunk {item['chunk_id']}]\n{item['text']}"
        )
    context = '\n\n'.join(context_parts)

    prompt = f"""You are a helpful document question-answering assistant.
Answer the user's question using ONLY the CONTEXT below.
If the context does not contain the answer, clearly say: \"I couldn't find that information in the provided documents.\"
Do not invent facts. Keep the answer clear and reasonably concise. When possible, mention the source number.

CONTEXT:
{context}

QUESTION: {question}

ANSWER:"""

    response = requests.post(
        f'{OLLAMA_API}/api/generate',
        json={
            'model': CHAT_MODEL,
            'prompt': prompt,
            'stream': False,
            'options': {'temperature': 0.2, 'num_predict': 300}
        },
        timeout=300
    )
    response.raise_for_status()
    answer = response.json().get('response', '').strip()

    print('\n🤖 ANSWER\n' + '=' * 60)
    print(answer)
    print('\n📚 RETRIEVED SOURCES\n' + '=' * 60)
    for rank, idx in enumerate(best_indices, start=1):
        item = chunks[idx]
        print(f"{rank}. {item['source']} | chunk {item['chunk_id']} | similarity: {scores[idx]:.3f}")
        print(item['text'][:350] + ('...' if len(item['text']) > 350 else ''))
        print()

    return answer

