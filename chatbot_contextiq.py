"""## 4. Split documents into overlapping chunks

Chunking keeps retrieved context focused while overlap helps avoid cutting important information at chunk boundaries.
"""

def split_into_chunks(text, chunk_size=120, overlap=25):
    words = text.split()
    if not words:
        return []
    chunks = []
    step = max(1, chunk_size - overlap)
    for start in range(0, len(words), step):
        piece = words[start:start + chunk_size]
        if piece:
            chunks.append(' '.join(piece))
        if start + chunk_size >= len(words):
            break
    return chunks

